import mongoose from "mongoose";
import ResearchNote, { IResearchNote, ResearchNoteType, HypothesisStatus } from "../models/ResearchNote";
import ResearchProject from "../models/ResearchProject";
import ResearchPaper from "../models/ResearchPaper";

export const researchNoteService = {
  /**
   * Create a new research note attached to a project and optionally papers
   */
  createNote: async (
    data: {
      projectId: string;
      paperId?: string;
      paperIds?: string[];
      title?: string;
      content: string;
      noteType?: ResearchNoteType;
      hypothesisStatus?: HypothesisStatus;
      aiGenerated?: boolean;
      aiAssisted?: boolean;
      sourceText?: string;
      tags?: string[];
      excerpt?: string;
      isPinned?: boolean;
    },
    ownerId?: string
  ): Promise<IResearchNote> => {
    if (!mongoose.isValidObjectId(data.projectId)) {
      throw new Error("Invalid project ID format");
    }

    const project = await ResearchProject.findById(data.projectId);
    if (!project) {
      throw new Error("Research project not found");
    }

    if (ownerId && mongoose.isValidObjectId(ownerId)) {
      const requesterOid = new mongoose.Types.ObjectId(ownerId);
      const isOwner = project.ownerId && project.ownerId.equals(requesterOid);
      const collab = project.collaborators?.find((c) => c.researcherId.equals(requesterOid));

      if (!isOwner && !collab) {
        throw new Error("Unauthorized: You do not have permission to add notes to this project");
      }

      if (collab && (collab.role === "viewer" || collab.role === "reviewer")) {
        throw new Error("Forbidden: Viewers and reviewers have read-only access and cannot create or edit research notes");
      }
    }

    let validPaperId: mongoose.Types.ObjectId | undefined = undefined;
    if (data.paperId && mongoose.isValidObjectId(data.paperId)) {
      const paper = await ResearchPaper.findById(data.paperId);
      if (paper) {
        validPaperId = paper._id as mongoose.Types.ObjectId;
      }
    }

    const validPaperIds: mongoose.Types.ObjectId[] = [];
    if (data.paperIds && Array.isArray(data.paperIds)) {
      data.paperIds.forEach((pid) => {
        if (mongoose.isValidObjectId(pid)) {
          validPaperIds.push(new mongoose.Types.ObjectId(pid));
        }
      });
    }
    if (validPaperId && !validPaperIds.some((id) => id.equals(validPaperId!))) {
      validPaperIds.push(validPaperId);
    }

    const resolvedOwnerId =
      ownerId && mongoose.isValidObjectId(ownerId)
        ? new mongoose.Types.ObjectId(ownerId)
        : project.ownerId || new mongoose.Types.ObjectId();

    const noteType = data.noteType || "general";
    // When creating a hypothesis note, status defaults to 'idea'.
    // If generated by AI, it can never automatically be marked 'supported'.
    let initialHypothesisStatus: HypothesisStatus | undefined = undefined;
    if (noteType === "hypothesis") {
      if (data.aiGenerated && data.hypothesisStatus === "supported") {
        throw new Error(
          "Academic integrity violation: AI cannot automatically declare a research hypothesis as supported. Only a researcher can validate and advance hypothesis status."
        );
      }
      initialHypothesisStatus = data.hypothesisStatus || "idea";
    }

    const note = await ResearchNote.create({
      ownerId: resolvedOwnerId,
      projectId: project._id,
      paperId: validPaperId,
      paperIds: validPaperIds,
      title: data.title?.trim() || "Untitled Research Note",
      content: data.content || "",
      noteType,
      hypothesisStatus: initialHypothesisStatus,
      aiGenerated: Boolean(data.aiGenerated),
      aiAssisted: Boolean(data.aiAssisted || data.aiGenerated),
      sourceText: data.sourceText?.trim(),
      tags: Array.isArray(data.tags) ? data.tags.filter(Boolean) : [],
      excerpt: data.excerpt?.trim(),
      isPinned: Boolean(data.isPinned),
    });

    // Add note to project.noteIds
    if (!project.noteIds) {
      project.noteIds = [];
    }
    project.noteIds.push(note._id as mongoose.Types.ObjectId);
    await project.save();

    const populated = await ResearchNote.findById(note._id)
      .populate("paperId", "title authors year venue")
      .populate("paperIds", "title authors year venue")
      .populate("projectId", "title domain currentStage")
      .lean();

    return (populated as unknown) as IResearchNote;
  },

  /**
   * Get all research notes for a project
   */
  getProjectNotes: async (
    projectId: string,
    ownerId?: string
  ): Promise<IResearchNote[]> => {
    if (!mongoose.isValidObjectId(projectId)) {
      throw new Error("Invalid project ID format");
    }

    const project = await ResearchProject.findById(projectId);
    if (!project) {
      throw new Error("Research project not found");
    }

    if (ownerId && mongoose.isValidObjectId(ownerId)) {
      const requesterOid = new mongoose.Types.ObjectId(ownerId);
      const isOwner = project.ownerId && project.ownerId.equals(requesterOid);
      const isCollab = project.collaborators?.some((c) => c.researcherId.equals(requesterOid));
      if (!isOwner && !isCollab) {
        throw new Error("Unauthorized: You do not have permission to view this project's notes");
      }
    }

    return ResearchNote.find({ projectId: new mongoose.Types.ObjectId(projectId) })
      .populate("paperId", "title authors year venue")
      .populate("paperIds", "title authors year venue")
      .populate("projectId", "title domain currentStage")
      .sort({ isPinned: -1, createdAt: -1 })
      .lean() as unknown as IResearchNote[];
  },

  /**
   * Get all research notes across all projects for an authenticated researcher
   */
  getAllResearcherNotes: async (
    ownerId: string,
    filters?: {
      projectId?: string;
      noteType?: string;
      search?: string;
    }
  ): Promise<IResearchNote[]> => {
    if (!ownerId || !mongoose.isValidObjectId(ownerId)) {
      throw new Error("Valid researcher ID is required to fetch notes");
    }

    const query: any = { ownerId: new mongoose.Types.ObjectId(ownerId) };

    if (filters?.projectId && mongoose.isValidObjectId(filters.projectId)) {
      query.projectId = new mongoose.Types.ObjectId(filters.projectId);
    }

    if (filters?.noteType && filters.noteType !== "all") {
      query.noteType = filters.noteType;
    }

    if (filters?.search && filters.search.trim()) {
      const searchRegex = new RegExp(filters.search.trim(), "i");
      query.$or = [
        { title: searchRegex },
        { content: searchRegex },
        { tags: searchRegex },
        { excerpt: searchRegex },
        { sourceText: searchRegex },
      ];
    }

    return ResearchNote.find(query)
      .populate("paperId", "title authors year venue")
      .populate("paperIds", "title authors year venue")
      .populate("projectId", "title domain currentStage")
      .sort({ isPinned: -1, updatedAt: -1 })
      .lean() as unknown as IResearchNote[];
  },

  /**
   * Update an existing research note
   */
  updateNote: async (
    noteId: string,
    updates: Partial<{
      title: string;
      content: string;
      noteType: ResearchNoteType;
      hypothesisStatus: HypothesisStatus;
      aiAssisted: boolean;
      sourceText: string;
      tags: string[];
      isPinned: boolean;
      excerpt: string;
      paperId?: string;
      paperIds?: string[];
    }>,
    ownerId?: string
  ): Promise<IResearchNote | null> => {
    if (!mongoose.isValidObjectId(noteId)) {
      throw new Error("Invalid note ID format");
    }

    const note = await ResearchNote.findById(noteId);
    if (!note) {
      return null;
    }

    if (ownerId && mongoose.isValidObjectId(ownerId)) {
      const reqOid = new mongoose.Types.ObjectId(ownerId);
      const isNoteOwner = note.ownerId && note.ownerId.equals(reqOid);
      let canEdit = isNoteOwner;
      if (!isNoteOwner && note.projectId) {
        const project = await ResearchProject.findById(note.projectId).lean();
        if (project) {
          const isProjectOwner = project.ownerId && project.ownerId.equals(reqOid);
          const collab = project.collaborators?.find((c) => c.researcherId.equals(reqOid));
          if (collab && (collab.role === "viewer" || collab.role === "reviewer")) {
            throw new Error("Forbidden: Viewers and reviewers have read-only access and cannot create or edit research notes");
          }
          if (isProjectOwner || (collab && (collab.role === "co_author" || collab.role === "contributor"))) {
            canEdit = true;
          }
        }
      }
      if (!canEdit) {
        throw new Error("Unauthorized: You do not have permission to edit this note");
      }
    }

    if (updates.title !== undefined) note.title = updates.title.trim();
    if (updates.content !== undefined) note.content = updates.content;
    if (updates.noteType !== undefined) note.noteType = updates.noteType;
    if (updates.hypothesisStatus !== undefined) note.hypothesisStatus = updates.hypothesisStatus;
    if (updates.aiAssisted !== undefined) note.aiAssisted = updates.aiAssisted;
    if (updates.sourceText !== undefined) note.sourceText = updates.sourceText.trim();
    if (updates.tags !== undefined) note.tags = updates.tags;
    if (updates.isPinned !== undefined) note.isPinned = updates.isPinned;
    if (updates.excerpt !== undefined) note.excerpt = updates.excerpt.trim();

    if (updates.paperId !== undefined) {
      if (updates.paperId && mongoose.isValidObjectId(updates.paperId)) {
        note.paperId = new mongoose.Types.ObjectId(updates.paperId);
      } else {
        note.paperId = undefined;
      }
    }

    if (updates.paperIds !== undefined && Array.isArray(updates.paperIds)) {
      note.paperIds = updates.paperIds
        .filter((id) => mongoose.isValidObjectId(id))
        .map((id) => new mongoose.Types.ObjectId(id));
    }

    await note.save();

    const populated = await ResearchNote.findById(note._id)
      .populate("paperId", "title authors year venue")
      .populate("paperIds", "title authors year venue")
      .populate("projectId", "title domain currentStage")
      .lean();

    return (populated as unknown) as IResearchNote;
  },

  /**
   * Delete a research note and unlink from project
   */
  deleteNote: async (
    noteId: string,
    ownerId?: string
  ): Promise<{ success: boolean; message: string }> => {
    if (!mongoose.isValidObjectId(noteId)) {
      throw new Error("Invalid note ID format");
    }

    const note = await ResearchNote.findById(noteId);
    if (!note) {
      throw new Error("Research note not found");
    }

    if (ownerId && mongoose.isValidObjectId(ownerId)) {
      if (note.ownerId && !note.ownerId.equals(new mongoose.Types.ObjectId(ownerId))) {
        throw new Error("Unauthorized: You do not have permission to delete this note");
      }
    }

    // Remove from project.noteIds
    await ResearchProject.findByIdAndUpdate(note.projectId, {
      $pull: { noteIds: note._id },
    });

    await ResearchNote.findByIdAndDelete(noteId);

    return { success: true, message: "Research note deleted successfully" };
  },

  /**
   * Get all research notes for an owner across all projects
   */
  getAllNotes: async (ownerId?: string, limit: number = 20): Promise<IResearchNote[]> => {
    const query: any = {};
    if (ownerId && mongoose.isValidObjectId(ownerId)) {
      query.ownerId = new mongoose.Types.ObjectId(ownerId);
    }

    return (ResearchNote.find(query)
      .populate("paperId", "title authors year venue")
      .populate("projectId", "title domain")
      .sort({ createdAt: -1 })
      .limit(limit)
      .lean() as unknown) as IResearchNote[];
  },
};

